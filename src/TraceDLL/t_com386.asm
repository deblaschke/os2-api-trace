;                                                                              ;
;  T_GetTID()                                                                  ;
;                                                                              ;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

        PUBLIC  T_GetTID

        ASSUME  CS:FLAT
CODE32  SEGMENT
        ALIGN   04H

T_GetTID        PROC
        PUSH    FS                              ; Save FS
        PUSH    150BH                           ; Push TIB selector
        POP     FS                              ; FS = TIB selector
        MOV     EAX, FS:[tib_ptib2]             ; EAX = TIB2 pointer
        MOV     EAX, [EAX].tib2_ultid           ; EAX = Thread identifier
        POP     FS                              ; Restore FS
        RET
T_GetTID        ENDP

CODE32  ENDS

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;                                                                              ;
;  T_RestoreRegs16()                                                           ;
;                                                                              ;
;  Upon entry EAX  contains the flat address of the  saved registers structure ;
;  because  T_RestoreRegs16 is not  declared as APIENTRY  in t_common.h.  As a ;
;  result,  the first parameter is passed to this routine in EAX instead of on ;
;  the stack.  All T_RestoreRegs16 does is  convert the structure's address to ;
;  16-bit and move it into EDX for the appropriate RestoreRegs below.          ;
;                                                                              ;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

        PUBLIC  T_RestoreRegs16

        ASSUME  CS:FLAT
CODE32  SEGMENT
        ALIGN   04H

T_RestoreRegs16 PROC
IFDEF T_16BIT
        CALL    DOS32FLATTOSEL                  ; EAX = 16-bit sRegs16 pointer
        MOV     EDX, EAX                        ; EDX = 16-bit sRegs16 pointer
ENDIF
        RET
T_RestoreRegs16 ENDP

CODE32  ENDS

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;                                                                              ;
;  T_SaveRegs16()                                                              ;
;                                                                              ;
;  Upon entry EAX  contains the flat address of the  saved registers structure ;
;  because  T_SaveRegs16  is not  declared as  APIENTRY  in t_common.h.  As  a ;
;  result,  the first parameter is passed to this routine in EAX instead of on ;
;  the stack.  T_SaveRegs16  initializes  the structure  and replaces  the API ;
;  caller's return CS:IP with the CS:IP of the appropriate RestoreRegs below.  ;
;                                                                              ;
;  NOTE: The "SHL ECX, 5" instruction is  dependent upon the alignment and the ;
;  ordering of the RestoreRegs routines  below.  The calculation is the number ;
;  of API parameter bytes  divided by two  multiplied  by the alignment.  This ;
;  requires  that the  RestoreRegs routines  be ordered sequentially  starting ;
;  with zero (RestoreRegs00) and that there be a RestoreRegs routine for every ;
;  two-byte increment.                                                         ;
;                                                                              ;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

        PUBLIC  T_SaveRegs16

        ASSUME  CS:FLAT
CODE32  SEGMENT
        ALIGN   04H

T_SaveRegs16    PROC
IFDEF T_16BIT
        PUSH    EBX                             ; Save EBX
        MOV     EBX, EAX                        ; EBX = sRegs16 pointer
        MOV     [EBX].regs16_usCX, CX           ; Save CX in sRegs16
        MOV     [EBX].regs16_usDX, DX           ; Save DX in sRegs16
        MOV     EAX, [EBP+4]                    ; EAX = API thunk's call frame
        MOV     EAX, [EAX]                      ; EAX = API caller's SS:BP
        CALL    DOS32SELTOFLAT                  ; EAX = API caller's EBP
        PUSH    EAX                             ; Save API caller's EBP
        MOV     EAX, [EAX+12]                   ; EAX = API caller's return CS:IP
        MOV     [EBX].regs16_ulCSIP, EAX        ; Save CS:IP in sRegs16
        MOV     EAX, OFFSET FLAT:RestoreRegs00  ; EAX = RestoreRegs00 EIP
        MOVZX   ECX, [EBX].regs16_usParmBytes   ; ECX = Parameter bytes
        SHL     ECX, 5                          ; ECX = ( Parm bytes / 2 ) * 64
        ADD     EAX, ECX                        ; EAX = RestoreRegsXX EIP
        CALL    DOS32FLATTOSEL                  ; EAX = RestoreRegsXX CS:IP
        MOV     ECX, EAX                        ; ECX = RestoreRegsXX CS:IP
        POP     EAX                             ; EAX = API caller's EBP
        MOV     [EAX+12], ECX                   ; Return to RestoreRegsXX instead of caller
        POP     EBX                             ; Restore EBX
ENDIF
        RET
T_SaveRegs16    ENDP

CODE32  ENDS

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;                                                                              ;
;  RestoreRegs00()                                                             ;
;                                                                              ;
;  Upon  entry EDX  contains the  segmented  address  of the  saved  registers ;
;  structure   because  of  T_RestoreReg16's   efforts  above.   RestoreRegs00 ;
;  restores the saved registers and returns  to the API caller for an API with ;
;  0 bytes of parameters.                                                      ;
;                                                                              ;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

IFDEF T_16BIT
        ASSUME  CS:CODE16
CODE16  SEGMENT
        ALIGN   40H

RestoreRegs00   PROC
        SUB     SP, 4                           ; Allocate CS:IP
        PUSH    BP                              ; Save BP
        MOV     BP,SP                           ; BP = Stack frame base pointer
        PUSH    DS                              ; Save DS
        PUSH    BX                              ; Save BX
        MOV     BX, DX                          ; BX = sRegs16 pointer offset
        ROR     EDX,16                          ; Switch segment and offset
        MOV     DS, DX                          ; DS = sRegs16 pointer segment
        MOV     ECX, DWORD PTR [BX].regs16_ulCSIP; ECX = API caller's return CS:IP
        MOV     DWORD PTR [BP+2], ECX           ; Return to API caller
        MOV     CX, WORD PTR [BX].regs16_usCX   ; Restore CX from sRegs16
        MOV     DX, WORD PTR [BX].regs16_usDX   ; Restore DX from sRegs16
        POP     BX                              ; Restore BX
        POP     DS                              ; Restore DS
        POP     BP                              ; Restore BP
        RETF
RestoreRegs00   ENDP

CODE16  ENDS
ENDIF

