;                                                                              ;
;  GetAPICaller16()                                                            ;
;                                                                              ;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

IFDEF T_16BIT
        PUBLIC  GetAPICaller16

        ASSUME  CS:FLAT
CODE32  SEGMENT
        ALIGN   04H

GetAPICaller16  PROC
        MOV     EAX, [EBP]                      ; EAX = Trace API's call frame
        MOV     EAX, [EAX+4]                    ; EAX = API thunk's call frame
        MOV     EAX, [EAX]                      ; EAX = API caller's SS:BP
        CALL    DOS32SELTOFLAT                  ; EAX = API caller's EBP
        MOV     EAX, [EAX+12]                   ; EAX = API caller's return CS:IP
        RET
GetAPICaller16  ENDP

CODE32  ENDS
ENDIF

