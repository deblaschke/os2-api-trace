;                                                                              ;
;  File name    : T_COM386.ASM                                                 ;
;                                                                              ;
;  Title        : OS/2 API trace DLL common Intel assembly routines            ;
;                                                                              ;
;  Author       : Dave Blaschke                                                ;
;                 deblaschke@yahoo.com                                         ;
;                                                                              ;
;  Description  : Common    Intel    assembly    routines:       GetAPICaller, ;
;                 GetAPICaller16, T_GetTID, T_RestoreRegs16, and T_SaveRegs16. ;
;                                                                              ;
;  Notes        : T_SaveRegs16 and T_RestoreRegs16  are required by all 16-bit ;
;                 Dos  APIs  because  of  an  undocumented  "feature"  of  the ;
;                 Microsoft  C  compiler.  Even  though  the 16-bit  OS/2  API ;
;                 calling convention does not  preserve CX or DX across an API ;
;                 call,  the Microsoft compiler  assumes that  these registers ;
;                 are preserved  across a call  directly into the  OS/2 kernel ;
;                 through a  call gate  because  the  register state  is saved ;
;                 upon entry  into the kernel and restored  upon exit from the ;
;                 kernel.  Unfortunately,  the  thunks  generated  by the  IBM ;
;                 VisualAge C++ compiler use ECX and EDX.                      ;
;                                                                              ;
;                 In a similar fashion,  T_SaveRegs16  and T_RestoreRegs16 are ;
;                 also required by all 16-bit Kbd, Mou, Vio APIs because most, ;
;                 if not all,  of these APIs perform a PUSHA  upon entry and a ;
;                 POPA  upon exit  even  though  the 16-bit  OS/2 API  calling ;
;                 convention does  not preserve  CX or DX  across an API call. ;
;                 Because some OS/2 applications,  such as TEDIT, know that CX ;
;                 and DX are preserved across these API calls,  they depend on ;
;                 the state  of one or  both of these  registers.  Once again, ;
;                 the thunks  generated by the IBM VisualAge C++  compiler use ;
;                 ECX and EDX.                                                 ;
;                                                                              ;
;                 As a result  of the above,  T_SaveRegs16  must be  the first ;
;                 code executed  when entering a 16-bit Dos,  Kbd, Mou, or Vio ;
;                 trace API,  and T_RestoreRegs16 must be executed immediately ;
;                 before the return statement  when exiting a 16-bit Dos, Kbd, ;
;                 Mou, or Vio trace API.                                       ;
;                                                                              ;
;  History      : Version Date    Item                                         ;
;                 2.30.00 12Jun95 Created (supported LX format  and 32-bit Dos ;
