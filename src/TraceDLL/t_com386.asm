;                                                                              ;
;  GetAPICaller()                                                              ;
;                                                                              ;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

        PUBLIC  GetAPICaller

        ASSUME  CS:FLAT
CODE32  SEGMENT
        ALIGN   04H

GetAPICaller    PROC
        MOV     EAX, [EBP]                      ; EAX = API caller's EBP
        MOV     EAX, [EAX+4]                    ; EAX = API caller's return EIP
        RET
GetAPICaller    ENDP

CODE32  ENDS

